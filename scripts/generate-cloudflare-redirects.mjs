/**
 * dist 内の directory 形式 HTML 向けに、末尾スラッシュなし → 付き 301 を dist/_redirects に書く。
 * Cloudflare は動的リダイレクト（splat）が最大 100 件のため、memo / blog / keywords は 1 本の splat にまとめる。
 *
 * @see https://developers.cloudflare.com/workers/static-assets/redirects/
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DIST = join(ROOT, 'dist');

/** 配下を `/*` 1 ルールに任せる（メモ件数で 100 動的上限を超えない） */
const REDIRECT_SPLAT_ROOTS = new Set(['blog', 'memo', 'keywords']);

if (!existsSync(DIST)) {
  console.error('generate-cloudflare-redirects: dist/ がありません。先に astro build を実行してください。');
  process.exit(1);
}

/** dist 上のディレクトリ名 → URL パス（セグメントごとに encodeURIComponent） */
function urlPathFromSegments(segments) {
  return segments.map((s) => encodeURIComponent(s)).join('/');
}

/** @param {string} dir @param {string[]} segments */
function collectTrailingSlash301(dir, segments = []) {
  /** @type {string[]} */
  const lines = [];

  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    if (ent.name.startsWith('.')) continue;
    if (ent.name === '_redirects') continue;

    const full = join(dir, ent.name);

    if (!ent.isDirectory()) continue;
    if (ent.name === '_astro') continue;

    const nextSegments = [...segments, ent.name];
    const splatRoot = nextSegments[0];

    if (splatRoot && REDIRECT_SPLAT_ROOTS.has(splatRoot) && nextSegments.length > 1) {
      continue;
    }

    const indexHtml = join(full, 'index.html');
    if (!existsSync(indexHtml)) {
      lines.push(...collectTrailingSlash301(full, nextSegments));
      continue;
    }

    const path = urlPathFromSegments(nextSegments);
    lines.push(`/${path} /${path}/ 301`);

    if (splatRoot && REDIRECT_SPLAT_ROOTS.has(splatRoot)) {
      continue;
    }
    lines.push(...collectTrailingSlash301(full, nextSegments));
  }

  return lines;
}

const staticRules = [...new Set(collectTrailingSlash301(DIST))].sort();
const splatRules = [...REDIRECT_SPLAT_ROOTS]
  .sort()
  .map((root) => `/${root}/* /${root}/:splat/ 301`);

const rules = [...staticRules, ...splatRules];

const body = [
  '# Generated by scripts/generate-cloudflare-redirects.mjs — dist/ 内はビルドのたびに上書き。',
  '# 末尾スラッシュなし → 付き 301（クエリは Cloudflare が保持）。html_handling は auto-trailing-slash のまま。',
  '# memo / blog / keywords の子路径は splat 3 本に集約（動的リダイレクト 100 件上限）。',
  ...rules,
  '',
].join('\n');

writeFileSync(join(DIST, '_redirects'), body, 'utf8');
console.log(
  `generate-cloudflare-redirects: wrote ${rules.length} rules (${staticRules.length} static + ${splatRules.length} splat) to dist/_redirects`,
);
